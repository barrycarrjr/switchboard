/**
 * Rules from one source.
 *
 * Every AI tool keeps its own global instruction file (`CLAUDE.md`, `AGENTS.md`,
 * `GEMINI.md`), and every account of that tool keeps its own copy. Kept by hand,
 * those copies drift: on the machine this was written for, one account had no
 * rules at all, another had a copy two months old, and the Codex copy held two
 * decisions no other copy had. Each was "the rules", and each was different.
 *
 * So the user names an ordered list of rule files once, and Switchboard builds
 * every tool's instruction file from that list, in every account folder it knows
 * about. The list lives in `customizations.json` as `rulesSources`. Editing a
 * source file and syncing is the only way the instruction files change; the
 * generated files say so at the top, so nobody edits the copy by mistake.
 *
 * Two deliberate limits:
 * - A source that is missing or unreadable stops the whole sync. Building the
 *   files from the sources that happen to be there would quietly drop a rule from
 *   every tool at once, which is worse than leaving the old files alone.
 * - Claude Code reads every file in `<home>/rules/` by itself. Where that folder
 *   already holds every source (typically because it is a link to the source
 *   folder), Claude already reads them, and writing a composed `CLAUDE.md` as well
 *   would load every rule twice. That home is reported and left alone.
 */

const GENERATED_MARK = 'Generated by Switchboard from the rule files listed below.';

/**
 * Tools that silently cut their global rules file short. Measured, not documented:
 * Antigravity (agy 1.4.x, 2026-11-03) kept the first 23,998 bytes of a 62,927 byte
 * GEMINI.md and reported the rest as "<truncated 38929 bytes>", so a rule past that
 * point simply did not exist for it. The budgets sit below the measured cut so the
 * header and the pointer lines have room. A tool not listed here is given the
 * whole text; Codex read the last section of the same 62,927 byte file.
 */
export const RULES_BYTE_BUDGET = {
  antigravity: 23000,
  gemini: 23000,
};

/** Show a path under the user's home as `~/...`, so the generated header reads the same on every machine. */
function displayPath(file, home) {
  const rel = path.relative(home, file);
  if (rel && !rel.startsWith('..') && !path.isAbsolute(rel)) return `~/${rel.split(path.sep).join('/')}`;
  return file.split(path.sep).join('/');
}

function realOrSelf(p) {
  try { return fs.realpathSync.native(p); } catch { return path.resolve(p); }
}

/** Is `file` inside `dir`, once links on either side are resolved? */
function isInside(file, dir) {
  const rel = path.relative(realOrSelf(dir), realOrSelf(file));
  return rel !== '' && !rel.startsWith('..') && !path.isAbsolute(rel);
}

/** The saved, ordered list of source files. */
export function loadRulesSources(file = customizationsFile()) {
  return loadCustomizationsState(file).rulesSources;
}

/** The shared AI folder rule files are meant to live in, when it is set and exists. */
function currentSharedFolder(home) {
  return activeSharedFolder(loadSettings(), { home });
}

/** The sources that sit outside the shared AI folder; none when there is no such folder. */
export function sourcesOutsideSharedFolder(sources, sharedFolder) {
  if (!sharedFolder) return [];
  return sources.filter((s) => !isInsideFolder(s, sharedFolder));
}

/**
 * Save the ordered list of source files. Each must exist now, so a typo is
 * caught when it is typed rather than on the next sync. An empty list switches
 * the feature off.
 *
 * With a shared AI folder set (and present), a newly added source must be inside
 * it: that folder is what gets backed up and restored, so a rule file elsewhere
 * would quietly fall out of every backup. A source saved before the folder was
 * set keeps working, so reordering or removing in an older list never fails.
 */
export function saveRulesSources(sources, file = customizationsFile(), { home = os.homedir(), sharedFolder = currentSharedFolder(home) } = {}) {
  // Windows PowerShell hands `~/x.md` over as typed, so expand it here rather than
  // resolve it against whatever folder the command happened to run in.
  const list = (Array.isArray(sources) ? sources : [])
    .map((s) => String(s ?? '').trim())
    .filter(Boolean)
    .map((s) => path.resolve(/^~(?=$|[\\/])/.test(s) ? path.join(home, s.slice(1)) : s));
  const missing = list.filter((s) => !fs.existsSync(s) || !fs.statSync(s).isFile());
  if (missing.length) throw new Error(`not a file: ${missing.join(', ')}`);
  const unique = [];
  for (const s of list) if (!unique.some((u) => samePath(u, s))) unique.push(s);
  // loadCustomizationsState answers an empty state for a file it cannot parse, and
  // saving that would wipe the installed-plugin list. Refuse instead, as every other
  // config write in Switchboard does.
  if (fs.existsSync(file)) {
    try { JSON.parse(fs.readFileSync(file, 'utf8')); } catch {
      throw new Error(`${file} will not parse; fix or move it before setting rule sources`);
    }
  }
  const state = loadCustomizationsState(file);
  const outside = sourcesOutsideSharedFolder(unique, sharedFolder)
    .filter((s) => !state.rulesSources.some((old) => samePath(old, s)));
  if (outside.length) {
    throw new Error(`rule file is outside the shared AI folder (${sharedFolder}): ${outside.join(', ')}. Move it into that folder, or change the folder with: switchboard settings shared-folder <folder>`);
  }
  saveCustomizationsState({ ...state, rulesSources: unique }, file);
  return unique;
}

/** Same file, once links and letter case are resolved? */
function sameFile(a, b) {
  return samePath(realOrSelf(a), realOrSelf(b));
}

/**
 * Does Claude already read this source from `<home>/rules/` by itself? True when the
 * folder is a link to where the source lives, when `rules/` holds a link to the
 * source under the same name, or when it holds a plain copy with the same text.
 */
function claudeRulesFolderHas(rulesDir, src, srcText) {
  if (isInside(src, rulesDir)) return true;
  const candidate = path.join(rulesDir, path.basename(src));
  if (!fs.existsSync(candidate)) return false;
  if (sameFile(candidate, src)) return true;
  try {
    return fs.readFileSync(candidate, 'utf8').replace(/\r\n/g, '\n').trim() === srcText;
  } catch {
    return false;
  }
}

/**
 * Read every source and join them, in order, under a header naming them.
 * Throws naming every source it could not read.
 *
 * With a byte budget (a tool that cuts its rules file short), whole sources are
 * kept in order for as long as they fit, and any that do not are named at the end
 * as files to read, rather than letting the tool cut one off mid-sentence without
 * saying so. A source is never split: half a rule can read as its opposite.
 */
export function composeRules(sources, { home = os.homedir(), budget = Infinity } = {}) {
  const parts = [];
  const unreadable = [];
  for (const src of sources) {
    try {
      parts.push({ src, text: fs.readFileSync(src, 'utf8').replace(/^\uFEFF/, '').replace(/\r\n/g, '\n').trim() });
    } catch {
      unreadable.push(src);
    }
  }
  if (unreadable.length) throw new Error(`cannot read rule source: ${unreadable.join(', ')}`);
  const header = [
    `<!-- ${GENERATED_MARK} Edit those files, not this one:`,
    '     the next Switchboard sync replaces this file.',
    ...sources.map((s) => `     - ${displayPath(s, home)}`),
    '-->',
  ].join('\n');
  const join = (kept, left) => {
    let text = `${header}\n\n${kept.map((p) => p.text).join('\n\n')}\n`;
    if (left.length) {
      text += [
        '',
        '## Rule files to read as well',
        '',
        'This tool only reads the start of a long rules file, so these files, which are part of',
        'the same rules, are not copied in here. Read each one before starting work:',
        '',
        ...left.map((p) => `- \`${displayPath(p.src, home)}\``),
        '',
      ].join('\n');
    }
    return text;
  };
  const full = join(parts, []);
  if (Buffer.byteLength(full, 'utf8') <= budget) return full;
  // Reserve room for every pointer line first, so adding one can never push the
  // kept text over the budget.
  const kept = [];
  const left = [];
  const room = budget - Buffer.byteLength(join([], parts), 'utf8');
  let used = 0;
  // Stop at the first file that does not fit, so the kept files and the listed
  // ones are still read in the order the user chose.
  for (const p of parts) {
    const size = Buffer.byteLength(p.text, 'utf8') + 2;
    if (!left.length && used + size <= room) { kept.push(p); used += size; } else left.push(p);
  }
  return join(kept, left);
}

/**
 * Work out, without writing anything, what a sync would do to each instruction
 * file. One entry per distinct file, so two tools sharing a file (Gemini and
 * Antigravity both read `~/.gemini/GEMINI.md`) are written once.
 *
 * Only tools Switchboard counts as available, and only account folders that
 * already exist, are touched: a sync must not create a folder for a tool that is
 * not there.
 *
 * @returns {{ text: string|null, targets: Array<{clientId: string, home: string, file: string, action: 'write'|'create'|'same'|'skip', reason?: string}> }}
 */
export function planRulesSync({
  sources = loadRulesSources(),
  clientIds = null,
  home = os.homedir(),
  envReader = readUserEnv,
  accountsPath = accountsFile(),
  installedToolIds = null,
} = {}) {
  if (!sources.length) return { text: null, texts: new Map(), targets: [] };
  // Read once up front, so a missing source refuses the sync before anything else.
  const text = composeRules(sources, { home });
  const clients = customizationClients({ home, envReader, accountsPath, installedToolIds })
    .filter((c) => c.available && (!clientIds || clientIds.includes(c.id)));

  // Group by file first: two tools can share one file, and then the smaller of
  // their budgets has to win or the tighter tool would be cut short again.
  const byFile = [];
  for (const client of clients) {
    for (const h of client.homes) {
      if (!fs.existsSync(h)) continue;
      const file = path.join(h, client.ruleFile);
      let entry = byFile.find((e) => samePath(e.file, file));
      if (!entry) {
        entry = { clientId: client.id, home: h, file, ruleFile: client.ruleFile, budget: Infinity };
        byFile.push(entry);
      }
      entry.budget = Math.min(entry.budget, RULES_BYTE_BUDGET[client.id] ?? Infinity);
    }
  }

  // A source that is also a file this sync writes would feed its own output back
  // in: every sync would wrap it in one more header, and the watcher would fire on
  // each write, forever. Refuse the whole sync rather than start that.
  const clash = byFile.filter((e) => sources.some((s) => sameFile(s, e.file)));
  if (clash.length) {
    throw new Error(`a rule source is also a file this sync writes: ${clash.map((e) => e.file).join(', ')}. Move its text into a separate source file first.`);
  }

  const sourceTexts = new Map(sources.map((s) => [s, fs.readFileSync(s, 'utf8').replace(/^\uFEFF/, '').replace(/\r\n/g, '\n').trim()]));
  const byBudget = new Map([[Infinity, text]]);
  const texts = new Map();
  const targets = [];
  for (const e of byFile) {
    const base = { clientId: e.clientId, home: e.home, file: e.file };
    if (e.ruleFile === 'CLAUDE.md' && sources.every((s) => claudeRulesFolderHas(path.join(e.home, 'rules'), s, sourceTexts.get(s)))) {
      // Left alone either way, but a CLAUDE.md an earlier sync generated would now
      // load every rule a second time, so say so rather than keep quiet about it.
      let stale = false;
      try { stale = fs.readFileSync(e.file, 'utf8').includes(GENERATED_MARK); } catch { /* no file */ }
      targets.push({
        ...base,
        action: 'skip',
        reason: stale
          ? 'reads the sources from its rules folder, but its CLAUDE.md is an older generated copy that loads them again; delete it'
          : 'reads the sources directly from its rules folder',
      });
      continue;
    }
    if (!byBudget.has(e.budget)) byBudget.set(e.budget, composeRules(sources, { home, budget: e.budget }));
    const want = byBudget.get(e.budget);
    texts.set(e.file, want);
    let current = null;
    try { current = fs.readFileSync(e.file, 'utf8').replace(/\r\n/g, '\n'); } catch { current = null; }
    const action = current === null ? 'create' : current === want ? 'same' : 'write';
    const target = { ...base, action };
    if (want !== text) target.reason = `this tool reads only about ${e.budget} bytes, so some files are listed to read instead of copied in`;
    targets.push(target);
  }
  return { text, texts, targets };
}

/**
 * The ordinary backups are pruned to the newest few, and every source edit now
 * rewrites every target, so within a few edits the file a person kept by hand
 * would be gone. Before the first time Switchboard replaces a file it did not
 * generate, keep one copy beside it under a name the pruning never touches.
 */
function keepHandWrittenCopy(file) {
  let current;
  try { current = fs.readFileSync(file, 'utf8'); } catch { return; }
  if (current.includes(GENERATED_MARK)) return;
  const keep = `${file}.before-switchboard-rules`;
  if (!fs.existsSync(keep)) fs.copyFileSync(file, keep);
}

/**
 * Bring every instruction file in line with the sources. Files already
 * identical are not rewritten, so running this often costs nothing and leaves
 * no backups behind; a file that changes is backed up beside itself first.
 * A file that cannot be written is reported and does not stop the others.
 */
export function syncRules(opts = {}) {
  const { dryRun = false, home = os.homedir() } = opts;
  const sources = opts.sources ?? loadRulesSources();
  const sharedFolder = opts.sharedFolder !== undefined ? opts.sharedFolder : currentSharedFolder(home);
  const outsideSharedFolder = sourcesOutsideSharedFolder(sources, sharedFolder);
  const plan = planRulesSync({ ...opts, sources });
  const results = plan.targets.map((t) => {
    if (dryRun || t.action === 'same' || t.action === 'skip') return t;
    try {
      keepHandWrittenCopy(t.file);
      writeCustomizationFile(t.file, plan.texts.get(t.file));
      return t;
    } catch (e) {
      return { ...t, action: 'failed', reason: e.message };
    }
  });
  return { dryRun, sources, targets: results, sharedFolder, outsideSharedFolder };
}

/**
 * Call `onChange` shortly after any source file changes, so an edit reaches every
 * tool without anyone running a command. The folders are watched rather than the
 * files: editors and atomic writers replace a file by renaming a new one over
 * it, and a watch held on the old file would go quiet after the first save. A
 * burst of events from one save is folded into a single call.
 *
 * Watching is best effort (a network drive may not support it), so callers
 * should also sync on a slow timer. Returns an object with `close()`.
 */
export function createRulesWatcher({ sources = loadRulesSources(), onChange, debounceMs = 1500, watch = fs.watch } = {}) {
  const byDir = new Map();
  for (const s of sources) {
    const dir = path.dirname(s);
    if (!byDir.has(dir)) byDir.set(dir, new Set());
    byDir.get(dir).add(path.basename(s).toLowerCase());
  }
  let timer = null;
  const fire = () => {
    if (timer) clearTimeout(timer);
    timer = setTimeout(() => { timer = null; onChange(); }, debounceMs);
  };
  const watchers = [];
  for (const [dir, names] of byDir) {
    try {
      watchers.push(watch(dir, (_event, name) => {
        // Some platforms report no name; treat that as "maybe ours" rather than miss an edit.
        if (!name || names.has(String(name).toLowerCase())) fire();
      }));
    } catch { /* this folder cannot be watched; the caller's timer covers it */ }
  }
  return {
    close() {
      if (timer) clearTimeout(timer);
      for (const w of watchers) { try { w.close(); } catch { /* already closed */ } }
    },
  };
}

